  // ------------------------------------------------------------------------
  function hardEvalF(idx, X) {
    const f = HARD_F[idx - 1];
    const x = X[f.arg - 1];
    return f.c0 + f.c1 * x + f.c2 * x * x + f.c3 * x * x * x;
  }

  function hardEvalE(e, t) {
    return e.d0 + e.d1 * t + e.d2 * t * t + e.d3 * t * t * t;
  }

  function hardDerivatives(t, X, plan) {
    const E = HARD_E.map(e => hardEvalE(e, t));
    const out = new Array(13);

    for (let i = 0; i < 13; i++) {
      const link = HARD_LINKS[i];

      let pos = 1;
      for (let k = 0; k < link.p.length; k++) pos *= hardEvalF(link.p[k], X);
      let neg = 1;
      for (let k = 0; k < link.n.length; k++) neg *= hardEvalF(link.n[k], X);

      let sumPos = 0;
      for (let k = 0; k < link.pe.length; k++) sumPos += E[link.pe[k]];
      if (link.pe.length === 0) sumPos = 1;

      let sumNeg = 0;
      for (let k = 0; k < link.ne.length; k++) sumNeg += E[link.ne[k]];
      if (link.ne.length === 0) sumNeg = 1;

      let posTerm = pos * sumPos;
      let negTerm = neg * sumNeg;

      if (plan === 'p2' && i === 6) {
        posTerm *= MODEL.P2_POS_FACTOR;
        negTerm *= MODEL.P2_NEG_FACTOR;
      }

      let rate = (posTerm - negTerm) / HARD_NORM;
      if (!Number.isFinite(rate)) rate = 0;
      if (plan === 'p3') rate *= MODEL.P3_RATE;

      out[i] = clamp(rate, -MODEL.DX_LIMIT, MODEL.DX_LIMIT);
    }

    return out;
  }

  const plan = (params && params.plan) || 'p1';
  const steps = Math.round(MODEL.T_MAX / HARD_H);
  const tArr = [];
  const series = Array.from({ length: 13 }, () => []);
  const derivs = Array.from({ length: 13 }, () => []);
  let diverged = false;

  let X = HARD_INITIAL.map(v => clamp(v, 0, 1));

  for (let s = 0; s <= steps; s++) {
    const t = +(s * HARD_H).toFixed(6);
    tArr.push(t);
    for (let i = 0; i < 13; i++) series[i].push(X[i]);

    const k1 = hardDerivatives(t, X, plan);
    for (let i = 0; i < 13; i++) derivs[i].push(k1[i]);
    if (s === steps) break;

    const X2 = X.map((v, i) => v + 0.5 * HARD_H * k1[i]);
    const k2 = hardDerivatives(t + 0.5 * HARD_H, X2, plan);

    const X3 = X.map((v, i) => v + 0.5 * HARD_H * k2[i]);
    const k3 = hardDerivatives(t + 0.5 * HARD_H, X3, plan);

    const X4 = X.map((v, i) => v + HARD_H * k3[i]);
    const k4 = hardDerivatives(t + HARD_H, X4, plan);

    X = X.map((v, i) => v + (HARD_H / 6) * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]));

    if (X.some(v => !Number.isFinite(v) || Math.abs(v) > 20)) diverged = true;

    X = X.map((v, i) => {
      if (!Number.isFinite(v)) return HARD_INITIAL[i];
      return v < 0 ? 0 : v;
    });
  }

  const dense = buildDenseSeries(tArr, series, derivs, HARD_DENSE_PER_STEP);

  return {
    tArr,
    series,
    derivs,
    dense,
    diverged,
    fittedPolys: series.map((_, i) => fitQuadratic(dense.tArr, dense.series[i]))
  };
